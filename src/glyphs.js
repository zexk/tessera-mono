  TESSERA.boxDrawingClean = function (cp) {
    const code = BOX[cp];
    if (!code) return null;
    const out = new Uint8Array(16);
    const set = (x, y) => { if (x>=0&&x<8&&y>=0&&y<16) out[y] |= (1 << (7 - x)); };
    const [L, R, U, D] = code;
    const mx = 3, my = 7;
    // Rounded corners (U+256D–U+2570): shift each arm 1px away from the junction,
    // leaving the corner cell empty. The notch reads as a curve at bitmap scale.
    const ro = (cp >= 0x256d && cp <= 0x2570) ? 1 : 0;
    const drawH = (x0, x1, y, w) => {
      if (w === 1) for (let x = x0; x <= x1; x++) set(x, y);
      else if (w === 2) for (let x = x0; x <= x1; x++) { set(x, y); set(x, y+1); }
      else if (w === 3) for (let x = x0; x <= x1; x++) { set(x, y-1); set(x, y+1); }
    };
    const drawV = (y0, y1, x, w) => {
      if (w === 1) for (let y = y0; y <= y1; y++) set(x, y);
      else if (w === 2) for (let y = y0; y <= y1; y++) { set(x, y); set(x+1, y); }
      else if (w === 3) for (let y = y0; y <= y1; y++) { set(x-1, y); set(x+1, y); }
    };
    if (L) drawH(0, mx - ro, my, L);
    if (R) drawH(mx + ro, 7, my, R);
    if (U) drawV(0, my - ro, mx, U);
    if (D) drawV(my + ro, 15, mx, D);
    return out;
  };

  // Block elements (U+2580..259F)
  TESSERA.blockElement = function (cp) {
    const out = new Uint8Array(16);
    const set = (x, y) => { out[y] |= (1 << (7 - x)); };
    const fillRect = (x0, y0, x1, y1) => {
      for (let y = y0; y < y1; y++) for (let x = x0; x < x1; x++) set(x, y);
    };
    switch (cp) {
      case 0x2580: fillRect(0, 0, 8, 8); break;   // ▀ upper half
      case 0x2584: fillRect(0, 8, 8, 16); break;  // ▄ lower half
      case 0x2588: fillRect(0, 0, 8, 16); break;  // █ full
      case 0x258c: fillRect(0, 0, 4, 16); break;  // ▌ left half
      case 0x2590: fillRect(4, 0, 8, 16); break;  // ▐ right half
      case 0x2591: // ░ light shade
        for (let y = 0; y < 16; y++) for (let x = 0; x < 8; x++)
          if (((x + y) & 3) === 0) set(x, y);
        break;
      case 0x2592: // ▒ medium shade
        for (let y = 0; y < 16; y++) for (let x = 0; x < 8; x++)
          if (((x + y) & 1) === 0) set(x, y);
        break;
      case 0x2593: // ▓ dark shade
        for (let y = 0; y < 16; y++) for (let x = 0; x < 8; x++)
          if (((x + y) & 3) !== 0) set(x, y);
        break;
      case 0x2581: fillRect(0, 14, 8, 16); break;
      case 0x2582: fillRect(0, 12, 8, 16); break;
      case 0x2583: fillRect(0, 10, 8, 16); break;
      case 0x2585: fillRect(0, 6, 8, 16); break;
      case 0x2586: fillRect(0, 4, 8, 16); break;
      case 0x2587: fillRect(0, 2, 8, 16); break;
      case 0x2589: fillRect(0, 0, 7, 16); break;
      case 0x258a: fillRect(0, 0, 6, 16); break;
      case 0x258b: fillRect(0, 0, 5, 16); break;
      case 0x258d: fillRect(0, 0, 3, 16); break;
      case 0x258e: fillRect(0, 0, 2, 16); break;
      case 0x258f: fillRect(0, 0, 1, 16); break;
      default: return null;
    }
    return out;
  };

  // Braille patterns (U+2800..U+28FF) — a 2×4 grid of 2×2-px dots.
  // Dot N is bit (N-1) of (cp - 0x2800); the standard 8-dot layout is
  //   1 4     left column → px cols 1-2, right column → px cols 5-6
  //   2 5     the four rows  → px rows 1-2 / 5-6 / 9-10 / 13-14
  //   3 6     1-px margins all round, so dots stay perfectly centred on
  //   7 8     the even cell and tile seamlessly into the neighbours.
  const BRAILLE_DOTS = [ // bit index → [gridCol, gridRow]
    [0, 0], [0, 1], [0, 2], [1, 0], [1, 1], [1, 2], [0, 3], [1, 3],
  ];
  TESSERA.braille = function (cp) {
    if (cp < 0x2800 || cp > 0x28ff) return null;
    const bits = cp - 0x2800;
    const out = new Uint8Array(16);
    const dot = (gx, gy) => {
      const x = gx ? 5 : 1, y = 1 + gy * 4; // 2-px-wide dot at cols x,x+1
      out[y]     |= 3 << (6 - x);
      out[y + 1] |= 3 << (6 - x);
    };
    for (let i = 0; i < 8; i++)
      if (bits & (1 << i)) dot(BRAILLE_DOTS[i][0], BRAILLE_DOTS[i][1]);
    return out;
  };

  // —— Master glyph lookup ——
  TESSERA.getGlyph = function (cp) {
    if (GLYPHS[cp]) return GLYPHS[cp];
    const dia = TESSERA.DIACRITICS[cp];
    if (dia) {
      const base = GLYPHS[dia[0].charCodeAt(0)];
      const acc = TESSERA.ACCENTS[dia[1]];
      if (!base || !acc) return null;
      const out = new Uint8Array(16);
      for (let i = 0; i < 16; i++) out[i] = base[i] | acc[i];
      return out;
    }
    if (cp >= 0x2500 && cp <= 0x257f) return TESSERA.boxDrawingClean(cp);
    if (cp >= 0x2580 && cp <= 0x259f) return TESSERA.blockElement(cp);
    if (cp >= 0x2800 && cp <= 0x28ff) return TESSERA.braille(cp);
    return null;
  };

  // —— Variant transforms ——
  // Bold: right-dilate filled pixels (preserves outer shape, thickens strokes).
  TESSERA.bolden = function (g, level) {
    // level: 1 = bold, 2 = extra-bold (also down-dilate)
    if (!g) return g;
    const out = new Uint8Array(16);
    for (let y = 0; y < 16; y++) {
      let row = g[y];
      let dil = row | ((row >>> 1) & 0xff);
      out[y] = dil & 0xff;
    }
    if (level >= 2) {
      const out2 = new Uint8Array(16);
      for (let y = 0; y < 16; y++) out2[y] = out[y] | (y > 0 ? out[y-1] : 0);
      return out2;
    }
    return out;
  };
