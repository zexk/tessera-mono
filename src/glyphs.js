  // Parse a multiline string into a Uint8Array of 16 row bytes.
  // Each row of 8 chars becomes one byte (high bit = leftmost pixel).
  function G(s) {
    const rows = s.split('\n').filter(r => r.length >= 8);
    const out = new Uint8Array(16);
    for (let i = 0; i < 16; i++) {
      const r = (rows[i] || '........').slice(0, 8);
      let n = 0;
      for (let j = 0; j < 8; j++) if (r[j] === '#') n |= (1 << (7 - j));
      out[i] = n;
    }
    return out;
  }
