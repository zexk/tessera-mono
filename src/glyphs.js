  // —— Box drawing (U+2500..257F) — algorithmic but core set is curated ——
  // We render box-drawing chars programmatically via boxDrawing() below.
  TESSERA.BOX_RANGE = [0x2500, 0x257f];

  // boxDrawing(cp) -> Uint8Array(16). Each cell is divided into 4 arms
  // (left, right, up, down) with stroke weights.
  // Encoding from the Unicode chart (light/heavy/double).
  function boxDrawing(cp) {
    if (cp < 0x2500 || cp > 0x257f) return null;
    const out = new Uint8Array(16);
    const set = (x, y) => { if (x>=0&&x<8&&y>=0&&y<16) out[y] |= (1 << (7 - x)); };

    // Cell midpoint
    const mx = 3, my = 7; // visually centered for our cell

    // Helper: horizontal arm from (x0..x1, y), optionally thick (2 rows)
    const hArm = (x0, x1, y, thick) => {
      for (let x = x0; x <= x1; x++) { set(x, y); if (thick) set(x, y+1); }
    };
    const vArm = (y0, y1, x, thick) => {
      for (let y = y0; y <= y1; y++) { set(x, y); if (thick) set(x+1, y); }
    };
    const dblH = (x0, x1, y) => { for (let x = x0; x <= x1; x++) { set(x, y); set(x, y+2); } };
    const dblV = (y0, y1, x) => { for (let y = y0; y <= y1; y++) { set(x, y); set(x+2, y); } };

    // Map the 128 box-drawing characters
    const c = cp - 0x2500;
    switch (c) {
      // Horizontal lines
      case 0x00: hArm(0, 7, my); break;                 // ─
      case 0x01: for (let x = 0; x < 8; x += 2) set(x, my); break; // ╌
      case 0x02: hArm(0, 7, my, true); break;           // ━
      case 0x03: for (let x = 0; x < 8; x += 2) { set(x, my); set(x, my+1); } break; // ╍
      case 0x04: for (let x = 0; x < 8; x += 3) set(x, my); break; // ┄ light triple dash
      case 0x05: for (let x = 0; x < 8; x += 3) { set(x, my); set(x, my+1); } break; // ┅
      case 0x06: for (let x = 0; x < 8; x += 2) set(x, my); break; // ┈ quad dash light
      case 0x07: for (let x = 0; x < 8; x += 2) { set(x, my); set(x, my+1); } break; // ┉
      // Vertical lines
      case 0x02 + 14 - 14: break; // (placeholder noop)
      case 0x14 - 14 + 0x02: break; // (noop)
      // We'll fall through to default handling below for the rest:
      default: {
        // Decode by category
        if (c >= 0x00 && c <= 0x0b) {
          // mostly horizontals already; handle bold/double here
          hArm(0, 7, my);
          break;
        }
        if (c === 0x02) { hArm(0, 7, my, true); break; }
        if (c === 0x0a || c === 0x0b) { hArm(0, 7, my, true); break; }
        // Vertical bars
        if (c === 0x0c) { vArm(0, 15, mx); break; }            // │
        if (c === 0x0e) { vArm(0, 15, mx, true); break; }      // ┃
        if (c === 0x4c) { dblV(0, 15, mx-1); break; }          // ║

        // Corners (light)
        if (c === 0x0c + 4) { hArm(mx, 7, my); vArm(my, 15, mx); break; }   // ┌
        if (c === 0x10) { hArm(mx, 7, my); vArm(my, 15, mx); break; }       // ┌
        if (c === 0x14) { hArm(0, mx, my); vArm(my, 15, mx); break; }       // ┐
        if (c === 0x18) { hArm(mx, 7, my); vArm(0, my, mx); break; }        // └
        if (c === 0x1c) { hArm(0, mx, my); vArm(0, my, mx); break; }        // ┘
        // Tees
        if (c === 0x2c) { hArm(0, 7, my); vArm(my, 15, mx); break; }        // ┬
        if (c === 0x34) { hArm(0, 7, my); vArm(0, my, mx); break; }         // ┴
        if (c === 0x1c + 8) { vArm(0, 15, mx); hArm(mx, 7, my); break; }    // ├ (0x24)
        if (c === 0x24) { vArm(0, 15, mx); hArm(mx, 7, my); break; }        // ├
        if (c === 0x2c - 4) { vArm(0, 15, mx); hArm(0, mx, my); break; }    // ┤ (0x28)
        if (c === 0x28) { vArm(0, 15, mx); hArm(0, mx, my); break; }        // ┤
        if (c === 0x3c) { hArm(0, 7, my); vArm(0, 15, mx); break; }         // ┼

        // Double-line corners/crosses (basic subset)
        if (c === 0x54) { dblH(mx-1, 7, my-1); dblV(my, 15, mx-1); break; } // ╔
        if (c === 0x57) { dblH(0, mx+1, my-1); dblV(my, 15, mx-1); break; } // ╗
        if (c === 0x5a) { dblH(mx-1, 7, my-1); dblV(0, my-1, mx-1); break; } // ╚
        if (c === 0x5d) { dblH(0, mx+1, my-1); dblV(0, my-1, mx-1); break; } // ╝
        if (c === 0x6c) { dblH(0, 7, my-1); dblV(0, 15, mx-1); break; } // ╬

        // Default: render small dot to indicate not-yet-detailed glyph
        set(mx, my); set(mx+1, my); set(mx, my+1); set(mx+1, my+1);
      }
    }
    return out;
  }
  TESSERA.boxDrawing = boxDrawing;

