// 8 cols × 16 rows per cell. '#' = filled, '.' = empty.
// Vertical metrics:
//   row 0      : top margin (accent space)
//   row 1      : ascender top / tall accents
//   rows 2-10  : cap height (9 rows)   |  rows 4-10 : x-height (7 rows)
//   row 10     : baseline (last cap/x row)
//   rows 11-12 : descender
//   rows 13-15 : line gap

